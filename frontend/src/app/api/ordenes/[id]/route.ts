import {
  idValido,
  reenviarAlBackend,
  respuestaNoEncontrado,
} from "@/lib/backend-sesion";
import type { NextRequest } from "next/server";

// PATCH /api/ordenes/:id — editar los datos de la recepción.
export async function PATCH(
  request: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const { id } = await params;
  if (!idValido(id)) return respuestaNoEncontrado("Orden no encontrada");
  return reenviarAlBackend(request, `/ordenes/${id}`, "PATCH");
}
